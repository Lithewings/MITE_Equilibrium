    public static String getStandardBlockName(Block block) {
        if (block == null) {
            return null;
        }

        // 1. 获取方块在注册表中的标识符（Identifier）
        Identifier blockId = Registries.BLOCK.getId(block);
        if (blockId.getPath().isEmpty()) {
            return null;
        }

        // 2. 提取路径部分（如"minecraft:bedrock" → "bedrock"），并转为大写+替换下划线
        String path = blockId.getPath();


        //大写
        return path.toUpperCase();
    }







